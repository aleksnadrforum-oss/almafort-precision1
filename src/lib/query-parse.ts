// Разбор «живой» строки из сметы: инженерный сленг, аббревиатуры, количество.
// Пример: «болт м8 длинный оцинк штук 100» → сущность «болт», размер «М8»,
// покрытие «оцинкованный», количество 100; мусорные слова отбрасываются.

export type ParsedQuery = {
  /** Очищенная строка для поискового индекса. */
  clean: string;
  /** Сущность: тип изделия («болт», «гайка», «заглушка», «опора»…). */
  entity: string | null;
  /** Стандарт: DIN 912, ГОСТ 7798… */
  standard: string | null;
  /** Размерность: М8, М10х30, Ø108. */
  size: string | null;
  /** Материал/покрытие: оцинкованный, нержавеющая сталь. */
  finish: string | null;
  /** Количество из строки сметы, если указано. */
  quantity: number | null;
};

/** Слова-паразиты из смет: на поиск не влияют, только шумят. */
const NOISE = new Set([
  "шт", "штук", "штуки", "штука", "штк", "пожалуйста", "нужен", "нужны", "нужно",
  "надо", "купить", "цена", "стоимость", "поз", "позиция", "комплект", "длинный",
  "короткий", "обычный", "простой", "качественный", "хороший", "срочно", "с", "на",
  "для", "и", "или", "по", "в", "от", "до",
]);

/** Сленг и сокращения → нормальные слова каталога. */
const SYNONYMS: Record<string, string> = {
  оцинк: "оцинкованный",
  оц: "оцинкованный",
  цинк: "оцинкованный",
  нерж: "нержавеющая",
  нержавейка: "нержавеющая",
  нержа: "нержавеющая",
  а2: "нержавеющая",
  a2: "нержавеющая",
  а4: "нержавеющая",
  жц: "оцинкованный",
  саморез: "саморез",
  болты: "болт",
  гайки: "гайка",
  шайбы: "шайба",
  анкера: "анкер",
  анкеры: "анкер",
  заглушки: "заглушка",
  опоры: "опора",
  винты: "винт",
  шпильки: "шпилька",
  кронштейны: "кронштейн",
  крепеж: "крепёж",
};

const ENTITIES = [
  "болт", "гайка", "шайба", "винт", "саморез", "анкер", "шпилька", "заглушка",
  "опора", "кронштейн", "хомут", "дюбель", "крепёж", "профиль", "стойка",
];

const FINISHES = ["оцинкованный", "нержавеющая", "чёрный", "полимерный", "горячий"];

export function parseQuery(raw: string): ParsedQuery {
  const src = raw.toLowerCase().replace(/ё/g, "ё").trim();

  // DIN/ГОСТ/ISO
  const std = src.match(/\b(din|iso|гост|ту)\s?-?\s?(\d{2,5}(?:-\d+)?)/i);
  const standard = std ? `${std[1]!.toUpperCase()} ${std[2]}` : null;

  // Размерность: м8, м10х30, m6x20, ø108, d108
  // \b не работает с кириллицей — границу задаём явно.
  const sz = src.match(/(?:^|[^a-zа-я0-9])[мm]\s?(\d{1,3})(?:\s?[хx*]\s?(\d{1,4}))?/i);
  const dia = src.match(/[ø∅d]\s?(\d{2,4})/i);
  const size = sz
    ? `М${sz[1]}${sz[2] ? `х${sz[2]}` : ""}`
    : dia
      ? `Ø${dia[1]}`
      : null;

  // Количество: «штук 100», «100 шт», «х500»
  const qm =
    src.match(/(?:шт\.?|штук|штуки)\s*(\d{1,7})/) ??
    src.match(/(\d{1,7})\s*(?:шт\.?|штук|штуки|pcs)/) ??
    null;
  const quantity = qm ? Number(qm[1]) : null;

  const tokens = src
    .split(/[^a-zа-я0-9ёøx×х*.-]+/i)
    .map((t) => t.trim())
    .filter(Boolean)
    .map((t) => SYNONYMS[t] ?? t)
    .filter((t) => !NOISE.has(t))
    // голое число, совпавшее с количеством, в поиск не идёт
    .filter((t) => !(quantity !== null && t === String(quantity)));

  const entity = tokens.find((t) => ENTITIES.some((e) => t.startsWith(e.slice(0, 4)))) ?? null;
  const finish = tokens.find((t) => FINISHES.includes(t)) ?? null;

  const clean = [standard, size, ...tokens]
    .filter(Boolean)
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();

  return {
    clean: clean || raw.trim(),
    entity: entity ? entity[0]!.toUpperCase() + entity.slice(1) : null,
    standard,
    size,
    finish: finish ? finish[0]!.toUpperCase() + finish.slice(1) : null,
    quantity,
  };
}

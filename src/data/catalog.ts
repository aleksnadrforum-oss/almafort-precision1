/** Тир партии. Пороги берём из карточки товара — они разные по группам. */
export function tierOf(qty: number, p?: Product): 0 | 1 | 2 {
  const t1 = p?.tier1Qty ?? DEFAULT_TIER1;
  const t2 = p?.tier2Qty ?? DEFAULT_TIER2;
  if (qty >= t2) return 2;
  if (qty >= t1) return 1;
  return 0;
}

export function unitPrice(p: Product, qty: number) {
  const t = tierOf(qty, p);
  return t === 2 ? p.price5000 : t === 1 ? p.price1000 : p.price;
}
